def _get_gemini(tier: str = gemini.SMART):
    """Writing and fixing code is the reasoning tier; a 60s deadline because a
    whole file can come back."""
    class _W:
        def generate_content(self, contents):
            resp = gemini.call(contents, tier=tier, timeout_ms=60000)
            if resp is None:
                raise RuntimeError("every Gemini model on the ladder failed")
            return resp

    return _W()


def _clean_code(text: str) -> str:
    text = text.strip()
    text = re.sub(r"^```[a-zA-Z]*\n?", "", text)
    text = re.sub(r"\n?```$", "", text)
    return text.strip()


def _resolve_save_path(output_path: str, language: str) -> Path:
    ext_map = {
        "python": ".py", "py": ".py",
        "javascript": ".js", "js": ".js",
        "typescript": ".ts", "ts": ".ts",
        "html": ".html", "css": ".css",
        "java": ".java", "cpp": ".cpp", "c": ".c",
        "bash": ".sh", "shell": ".sh", "powershell": ".ps1",
        "sql": ".sql", "json": ".json", "rust": ".rs", "go": ".go",
    }
    if output_path:
        p = Path(output_path).expanduser()
        p = p if p.is_absolute() else DESKTOP / p
    else:
        ext = ext_map.get((language or "python").lower(), ".py")
        p = DESKTOP / f"jarvis_code{ext}"
    resolved = p.resolve()
    if not _is_within(resolved, Path.home().resolve()):
        raise ValueError("Output files must be saved inside your home folder.")
    return resolved


def _is_within(path: Path, root: Path) -> bool:
    return path == root or path.is_relative_to(root)


def _selected_file(file_path: str, player=None) -> tuple[Path | None, str]:
    if not file_path:
        return None, "No file path provided."
    try:
        p = Path(file_path).expanduser().resolve(strict=True)
        if not p.is_file():
            return None, f"Path is not a file: {file_path}"
        selected = getattr(player, "current_file", None)
        if selected and p == Path(selected).expanduser().resolve(strict=True):
            return p, ""

        home = Path.home()
        upload_roots = (
            Path(__file__).resolve().parent.parent / "uploads",
            home / "Downloads" / "JARVIS Uploads",
            home / "Documents" / "JARVIS Uploads",
        )
        for root in upload_roots:
            resolved_root = root.resolve()
            if _is_within(p, resolved_root):
                return p, ""
        return None, (
            "Access denied: select the file in the JARVIS UI or place it in a "
            "JARVIS Uploads folder first."
        )
    except (OSError, RuntimeError, ValueError):
        return None, f"File not found or cannot be accessed: {file_path}"


def _read_file(file_path: str, player=None) -> tuple[str, str]:
    p, err = _selected_file(file_path, player)
    if p is None:
        return "", err or "File is not available."
    if err:
        return "", err
    try:
        return p.read_text(encoding="utf-8"), ""
    except (OSError, UnicodeError) as e:
        return "", f"Could not read file: {e}"


def _atomic_write(path: Path, content: bytes) -> None:
    fd, temp_path = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(fd, "wb") as stream:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        if os.name != "nt":
            os.chmod(temp_path, 0o600)
        os.replace(temp_path, path)
    finally:
        try:
            os.unlink(temp_path)
        except FileNotFoundError:
            pass


def _save_file(path: Path, content: str) -> str:
    try:
        path = path.expanduser().resolve()
        if not _is_within(path, Path.home().resolve()):
            return "Could not save: output files must stay inside your home folder."
        if path.exists() and not path.is_file():
            return "Could not save: the output path is not a regular file."
        path.parent.mkdir(parents=True, exist_ok=True)
        existed = path.is_file()
        previous = (
            path.read_bytes()
            if existed and path.stat().st_size <= 1_000_000
            else None
        )
        encoded = content.encode("utf-8")
        _atomic_write(path, encoded)
        expected = hashlib.sha256(encoded).digest()

        def undo_write() -> str:
            if not path.exists() or not path.is_file():
                return f"'{path.name}' changed or disappeared; undo was not applied."
            try:
                if hashlib.sha256(path.read_bytes()).digest() != expected:
                    return f"'{path.name}' changed since it was saved; undo was not applied."
                if previous is None:
                    path.unlink()
                else:
                    _atomic_write(path, previous)
                return f"Restored the previous state of '{path.name}'."
            except OSError as exc:
                return f"Could not undo the save of '{path.name}': {exc}"

        if not existed or previous is not None:
            push_undo(f"Save code file {path.name}", undo_write)
            return f"Saved to: {path}"
        return f"Saved to: {path} (the previous file was too large to undo)"
    except Exception as e:
        return f"Could not save: {e}"


def _preview(code: str, lines: int = 10) -> str:
    all_lines = code.splitlines()
    preview   = "\n".join(all_lines[:lines])
    suffix    = f"\n... ({len(all_lines) - lines} more lines)" if len(all_lines) > lines else ""
    return preview + suffix


def _has_error(output: str) -> bool:
    error_signals = ["error", "exception", "traceback", "syntaxerror",
                     "nameerror", "typeerror", "stderr", "failed", "crash"]
    return any(s in output.lower() for s in error_signals)


