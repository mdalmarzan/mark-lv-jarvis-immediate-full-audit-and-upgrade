def _run_action(file_path, args, timeout, player) -> str:
    if not file_path:
        return "Please provide a file path to run, sir."
    p, err = _selected_file(file_path, player)
    if p is None:
        return err or "File is not available."
    if err:
        return err
    if player:
        player.write_log(f"[Code] Running {p.name}...")
    return _run_file(p, args, timeout)


def _optimize_action(file_path, code, language, output_path, player) -> str:

    if file_path and not code:
        code, err = _read_file(file_path, player)
        if err:
            return err
    if not code:
        return "Please provide code or a file path to optimize, sir."

    if player:
        player.write_log("[Code] Optimizing code...")

    lang  = language or "python"
    model = _get_gemini()

    prompt = f"""You are an expert {lang} developer and code reviewer.
Optimize the following code for:
1. Performance — eliminate unnecessary operations, use efficient data structures
2. Readability — clear variable names, proper formatting, logical structure
3. Best practices — modern {lang} patterns, error handling, type hints if applicable
4. Remove dead code, redundant comments, and unnecessary complexity

Return ONLY the optimized code — no explanation, no markdown, no backticks.

Original code:
{code[:6000]}

Optimized code:"""

    try:
        response  = model.generate_content(prompt)
        optimized = _clean_code(response.text)
    except Exception as e:
        return f"Could not optimize code: {e}"

    # Kaydet
    if file_path:
        save_path = Path(file_path)
    else:
        save_path = _resolve_save_path(output_path, lang)

    status = _save_file(save_path, optimized)
    if status.startswith("Could not save:"):
        return status
    print(f"[Code] ✅ Optimized: {save_path}")

    original_lines  = len(code.splitlines())
    optimized_lines = len(optimized.splitlines())
    diff = original_lines - optimized_lines

    return (
        f"Code optimized. {status}\n"
        f"Lines: {original_lines} → {optimized_lines} "
        f"({'−' if diff > 0 else '+'}{abs(diff)} lines)\n\n"
        f"Preview:\n{_preview(optimized)}"
    )


def _screen_debug_action(description, file_path, player, speak=None) -> str:

    if player:
        player.write_log("[Code] Taking screenshot for analysis...")

    print("[Code] 📸 Capturing screen for debug...")


    screenshot_path = _take_screenshot()
    if not screenshot_path:
        return "Could not take screenshot, sir. Please make sure PyAutoGUI is installed."


    file_content = ""
    if file_path:
        file_content, err = _read_file(file_path, player)
        if err:
            return err

    try:
        from google.genai import types

        image_bytes  = screenshot_path.read_bytes()
        image_base64 = _image_to_base64(screenshot_path)

        user_question = description or "What error or problem do you see on the screen? How can it be fixed?"

        context = ""
        if file_content:
            context = f"\n\nAdditionally, here is the related file content:\n```\n{file_content[:4000]}\n```"

        analysis_prompt = f"""You are an expert programmer and debugger analyzing a screenshot.

User's question: {user_question}{context}

Please:
1. Identify any errors, exceptions, or problems visible on the screen
2. Explain what is causing the problem in simple terms
3. Provide a concrete fix or solution
4. If there's code visible, show the corrected version

Be specific and actionable. If you see an error message, quote it exactly."""

        contents = [
            types.Part.from_bytes(data=image_bytes, mime_type="image/png"),
            analysis_prompt,
        ]

        response = gemini.call(contents, tier=gemini.SMART, timeout_ms=45_000)
        if response is None:
            return "Sir, I couldn't reach Gemini to analyse that screenshot."

        analysis = (response.text or "").strip()
        print(f"[Code] ✅ Screen analysis complete")

        try:
            screenshot_path.unlink()
        except Exception:
            pass

        if file_path and file_content:

            code_match = re.search(r"```[a-zA-Z]*\n(.*?)```", analysis, re.DOTALL)
            if code_match:
                fixed_code = code_match.group(1).strip()
                save_path  = Path(file_path)
                status = _save_file(save_path, fixed_code)
                if status.startswith("Could not save:"):
                    return status
                analysis += f"\n\n✅ Fixed code has been saved to: {file_path}"
                print(f"[Code] ✅ Fixed code saved: {file_path}")

        return analysis

    except Exception as e:

        try:
            screenshot_path.unlink()
        except Exception:
            pass
        return f"Screen analysis failed: {e}"


def code_helper(
    parameters: dict,
    response=None,
    player=None,
    session_memory=None,
    speak=None,
    _confirmed: bool = False,
) -> str:
    """
    Called from main.py.

    parameters:
        action      : write | edit | explain | run | build | screen_debug | optimize | auto
        description : What the code should do / what change to make / what problem to analyze
        language    : Programming language (default: python)
        output_path : Where to save — user specifies full path or filename
        file_path   : Path to existing file (edit / explain / run / build / optimize)
        code        : Raw code string (explain/optimize without a file)
        args        : CLI argument list for run/build
        timeout     : Execution timeout in seconds (default: 30)
    """
    if not isinstance(parameters, dict):
        return "Invalid code-helper arguments: expected an object."
    p           = parameters
    if not isinstance(p.get("action", "auto"), str):
        return "Invalid code-helper action: expected text."
    action      = p.get("action", "auto").lower().strip()
    description = p.get("description", "").strip()
    language    = p.get("language", "python").strip()
    output_path = p.get("output_path", "").strip()
    file_path   = p.get("file_path", "").strip()
    code        = p.get("code", "").strip()
    args        = p.get("args", [])
    timeout     = int(p.get("timeout", 30))

    if action == "auto":
        action = _detect_intent(description, file_path, code)
        print(f"[Code] 🤖 Auto-detected: {action}")

    if action not in _VALID_INTENTS:
        return f"Unknown code-helper action: {action}."
    if not isinstance(args, list) or any(not isinstance(arg, str) for arg in args):
        return "Code-helper args must be a list of strings."
    if not 1 <= timeout <= 300:
        return "Code-helper timeout must be between 1 and 300 seconds."

    selected_path = None
    if file_path and action in {"edit", "explain", "run", "optimize", "screen_debug"}:
        selected_path, error = _selected_file(file_path, player)
        if error:
            return error
        file_path = str(selected_path)
    elif action in {"edit", "run"} and not file_path:
        return "Please select a file first."
    elif action == "explain" and not file_path and not code:
        return "Please select a file or provide code first."

    target_path = None
    if action in {"write", "build"}:
        try:
            target_path = _resolve_save_path(output_path, language)
        except (OSError, RuntimeError, ValueError) as exc:
            return f"Invalid output path: {exc}"
    elif action in {"edit", "screen_debug"} and selected_path:
        target_path = selected_path
    elif action == "optimize":
        if selected_path:
            target_path = selected_path
        else:
            try:
                target_path = _resolve_save_path(output_path, language)
            except (OSError, RuntimeError, ValueError) as exc:
                return f"Invalid output path: {exc}"

    needs_confirmation = (
        action in {"run", "build"}
        or (target_path is not None and target_path.exists())
    )
    if needs_confirmation and not _confirmed:
        if action == "run":
            title = f"Run {target_path.name if target_path else Path(file_path).name}?"
            detail = (
                "This executes the selected code on your computer and may change "
                "files or system state."
            )
        elif action == "build":
            title = "Build and run generated code?"
            detail = (
                "JARVIS will create or overwrite a code file and execute it on "
                "your computer."
            )
        else:
            title = f"Overwrite {target_path.name}?"
            detail = (
                f"This will replace the existing file:\n{target_path}"
                if action != "screen_debug"
                else f"Screen debugging may replace code in:\n{target_path}"
            )
        return request_confirmation(
            f"code_helper:{action}",
            title,
            detail,
            lambda: code_helper(
                {**p, "action": action}, response=response, player=player,
                session_memory=session_memory, speak=speak, _confirmed=True,
            ),
        )

    if action == "write":
        return _write_action(description, language, output_path, player)

    elif action == "edit":
        return _edit_action(
            file_path,
            description or p.get("instruction", ""),
            player
        )

    elif action == "explain":
        return _explain_action(file_path, code, player)

    elif action == "run":
        return _run_action(file_path, args, timeout, player)

    elif action == "build":
        return _build(description, language, output_path, args, timeout, speak, player)

    elif action == "optimize":
        return _optimize_action(file_path, code, language, output_path, player)

    elif action == "screen_debug":
        return _screen_debug_action(description, file_path, player, speak)

    else:
        return f"Unknown action: '{action}'. Use write, edit, explain, run, build, optimize, or screen_debug."


